"""Generate exact critical-strip zero and Hardy Z(t) TikZ data via mpmath."""

from pathlib import Path

import mpmath as mp


T_MAX = 40.0
Z_SCALE = 0.115
NUM_SAMPLES = 360


def main() -> None:
    with mp.workdps(50):
        zeros = [mp.zetazero(index) for index in range(1, 7)]
        residuals = [abs(mp.zeta(zero)) for zero in zeros]
        if max(residuals) >= mp.mpf("1e-45"):
            raise ArithmeticError("The computed zeta zeros failed the residual check.")

        seventh_zero = mp.zetazero(7)
        if not (float(zeros[-1].imag) < T_MAX < float(seventh_zero.imag)):
            raise ValueError(
                f"Expected T_MAX={T_MAX} strictly between 6th and 7th zeros."
            )

        zero_heights = [float(z.imag) for z in zeros]

        # Build a dense grid on [0, T_MAX] that includes the exact zero heights
        # so the curve passes precisely through Re(s) = 1/2 at every zero.
        grid = [T_MAX * i / NUM_SAMPLES for i in range(NUM_SAMPLES + 1)]
        sample_ts = sorted(set(grid + zero_heights))

        curve_points: list[tuple[float, float]] = []
        raw_z_values: list[tuple[float, float]] = []
        for t in sample_ts:
            z_val = float(mp.siegelz(mp.mpf(str(t))))
            if t in zero_heights:
                z_val = 0.0
            sigma = 0.5 + Z_SCALE * z_val
            curve_points.append((sigma, t))
            raw_z_values.append((t, z_val))

        print("Imaginary parts:", ", ".join(mp.nstr(z.imag, 14) for z in zeros))
        print(
            "Maximum |zeta(s)| at the computed points:",
            mp.nstr(max(residuals), 4),
        )
        max_t, max_z = max(raw_z_values, key=lambda pair: pair[1])
        min_t, min_z = min(raw_z_values, key=lambda pair: pair[1])
        print(
            f"Max Z(t) = {max_z:.4f} at t = {max_t:.3f} (sigma = {0.5 + Z_SCALE * max_z:.4f})"
        )
        print(
            f"Min Z(t) = {min_z:.4f} at t = {min_t:.3f} (sigma = {0.5 + Z_SCALE * min_z:.4f})"
        )

    coord_lines = []
    for idx in range(0, len(curve_points), 4):
        chunk = " ".join(
            f"({sigma:.5f},{t:.5f})" for sigma, t in curve_points[idx : idx + 4]
        )
        coord_lines.append(f"    {chunk}")
    coords_block = "\n".join(coord_lines)

    out_path = Path(__file__).with_name("critical-strip-data.tex")
    content = "\n".join(
        [
            "% Auto-generated by plot_critical_strip.py using 50-digit mpmath arithmetic.",
            "% Coordinates are in critical-strip units: x = Re(s), y = Im(s) on [0, 40].",
            "\\providecommand{\\CoverCriticalZeros}{%",
            "  " + ", ".join(f"{h:.6f}" for h in zero_heights) + "%",
            "}",
            "\\providecommand{\\CoverFillHardyZArea}[1][]{%",
            "  \\fill[#1] (0.5,0) -- plot coordinates {",
            coords_block,
            f"  }} -- (0.5,{T_MAX:.1f}) -- cycle;%",
            "}",
            "\\providecommand{\\CoverDrawHardyZCurve}[1][]{%",
            "  \\draw[#1] plot coordinates {",
            coords_block,
            "  };%",
            "}",
        ]
    )
    out_path.write_text(content + "\n", encoding="utf-8")
    print(
        f"Wrote {out_path} ({len(curve_points)} curve samples, {len(zero_heights)} zeros)."
    )


if __name__ == "__main__":
    main()
